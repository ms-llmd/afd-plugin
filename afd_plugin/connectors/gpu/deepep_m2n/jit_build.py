"""Build-on-first-use for the vendored DeepEP and DeepGEMM torch extensions.

Adapted from FastAFD ``python/minisgl/kernel/{deepep_moe,deepgemm,build_utils}.py``
(``3c71619``). Each extension is compiled once per (sources, toolchain, NCCL,
GPU arch) signature into a cache directory and loaded from there; concurrent
ranks serialize on a file lock so only one compiles.

The vLLM 0.30 CUDA images ship nvcc under ``/usr/local/cuda`` but not every
header that torch's ``ATen/cuda`` headers include (for example
``cusparse.h``). Those come from torch's pip CUDA wheels
(``nvidia/cu13/include``) and are added with ``-isystem`` so they are searched
only after the toolkit's own headers.
"""

from __future__ import annotations

import fcntl
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import asdict, dataclass, field
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path
from types import ModuleType

import torch

CSRC_ROOT = Path(__file__).resolve().parent / "csrc"
DEFAULT_CACHE_ROOT = Path.home() / ".cache" / "afd_plugin"
DEFAULT_MAX_JOBS = "16"
# vLLM 0.30 ships CUDA 13 wheels; cu12 keeps older images working.
NCCL_DISTRIBUTIONS = ("nvidia-nccl-cu13", "nvidia-nccl-cu12")
SIGNATURE_FILE = "build.signature"

# Generic setup script: reads the JSON spec written next to it, so no Python
# source is generated by string formatting.
_SETUP_SCRIPT = """\
import json
import pathlib

import setuptools
from torch.utils.cpp_extension import BuildExtension, CUDAExtension

spec = json.loads(pathlib.Path(__file__).with_name("spec.json").read_text())
extra_compile_args = {"cxx": spec["cxx_flags"]}
if spec["nvcc_flags"]:
    extra_compile_args["nvcc"] = spec["nvcc_flags"]
    extra_compile_args["nvcc_dlink"] = ["-dlink"] if spec["rdc"] else []
setuptools.setup(
    name=spec["name"],
    ext_modules=[
        CUDAExtension(
            name=spec["name"],
            sources=spec["sources"],
            include_dirs=spec["include_dirs"],
            library_dirs=spec["library_dirs"],
            libraries=spec["libraries"],
            extra_compile_args=extra_compile_args,
            extra_link_args=spec["link_flags"],
        )
    ],
    cmdclass={"build_ext": BuildExtension},
)
"""


@dataclass(frozen=True)
class ExtensionSpec:
    """Everything needed to compile one vendored torch extension."""

    name: str
    sources: list[str]
    include_dirs: list[str]
    source_roots: list[str]
    cxx_flags: list[str] = field(default_factory=list)
    nvcc_flags: list[str] = field(default_factory=list)
    link_flags: list[str] = field(default_factory=list)
    libraries: list[str] = field(default_factory=list)
    library_dirs: list[str] = field(default_factory=list)
    # Relocatable device code needs a device-link step (DeepEP uses it).
    rdc: bool = False


def resolve_nvcc() -> str:
    if path := os.environ.get("CUDA_NVCC_EXECUTABLE"):
        return path
    if path := shutil.which("nvcc"):
        return path
    for candidate in (Path("/usr/local/cuda/bin/nvcc"),):
        if candidate.exists():
            return str(candidate)
    raise RuntimeError(
        "DeepEP/DeepGEMM need nvcc at runtime: set CUDA_NVCC_EXECUTABLE or put "
        "nvcc on PATH."
    )


def cuda_home() -> Path:
    return Path(resolve_nvcc()).resolve().parents[1]


def nccl_distribution() -> tuple[str, str]:
    for name in NCCL_DISTRIBUTIONS:
        try:
            return name, distribution(name).version
        except PackageNotFoundError:
            continue
    raise RuntimeError(f"None of {NCCL_DISTRIBUTIONS} is installed")


def nvidia_wheel_root() -> Path:
    """``site-packages/nvidia``: where the pip NCCL and CUDA wheels live."""
    name, _ = nccl_distribution()
    return Path(str(distribution(name).locate_file(""))) / "nvidia"


def nccl_include_and_lib() -> tuple[Path, Path]:
    nccl_root = nvidia_wheel_root() / "nccl"
    include_dir, lib_dir = nccl_root / "include", nccl_root / "lib"
    if not (include_dir / "nccl.h").exists():
        raise RuntimeError(f"Missing NCCL headers under {include_dir}")
    if not (lib_dir / "libnccl.so.2").exists():
        raise RuntimeError(f"Missing libnccl.so.2 under {lib_dir}")
    return include_dir, lib_dir


def pip_cuda_include_flags() -> list[str]:
    """``-isystem`` flags for torch's pip CUDA wheel headers (``cu*/include``)."""
    return [
        flag
        for path in sorted(nvidia_wheel_root().glob("cu*/include"))
        for flag in ("-isystem", str(path))
    ]


def cuda_runtime_lib_dirs() -> list[str]:
    """Directories providing ``libcudart`` and ``libnvrtc`` for linking."""
    home = cuda_home()
    candidates = [
        home / "lib64",
        *sorted(home.glob("targets/*/lib")),
        *sorted(nvidia_wheel_root().glob("cu*/lib")),
    ]
    found: list[str] = []
    for lib_dir in candidates:
        if any(lib_dir.glob("libcudart.so*")) or any(lib_dir.glob("libnvrtc.so*")):
            found.append(str(lib_dir))
    if not found:
        raise RuntimeError(f"No libcudart/libnvrtc found in {candidates}")
    return found


def _latest_mtime(roots: list[str]) -> float:
    return max(
        path.stat().st_mtime
        for root in roots
        for path in Path(root).rglob("*")
        if path.is_file()
    )


def _signature(spec: ExtensionSpec) -> str:
    major, minor = torch.cuda.get_device_capability()
    return json.dumps(
        {
            "spec": asdict(spec),
            "source_mtime": _latest_mtime(spec.source_roots),
            "nccl": nccl_distribution(),
            "torch": torch.__version__,
            "nvcc": resolve_nvcc(),
            "arch": f"{major}.{minor}",
        },
        sort_keys=True,
    )


@contextmanager
def _build_lock(build_dir: Path) -> Iterator[None]:
    with (build_dir / "build.lock").open("w", encoding="utf-8") as lock_file:
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)


def _built_so(build_dir: Path, name: str) -> Path | None:
    candidates = sorted((build_dir / "lib").glob(f"{name}*.so"))
    return candidates[0] if candidates else None


def _cached_so(build_dir: Path, spec: ExtensionSpec, signature: str) -> Path | None:
    so_path = _built_so(build_dir, spec.name)
    signature_path = build_dir / SIGNATURE_FILE
    if (
        so_path is not None
        and signature_path.exists()
        and signature_path.read_text(encoding="utf-8") == signature
    ):
        return so_path
    return None


def build_extension(spec: ExtensionSpec, build_dir: Path) -> Path:
    """Compile ``spec`` into ``build_dir`` unless an up-to-date build exists."""
    build_dir.mkdir(parents=True, exist_ok=True)
    signature = _signature(spec)
    if (so_path := _cached_so(build_dir, spec, signature)) is not None:
        return so_path
    with _build_lock(build_dir):
        if (so_path := _cached_so(build_dir, spec, signature)) is not None:
            return so_path
        lib_dir = build_dir / "lib"
        temp_root = build_dir / "temp"
        lib_dir.mkdir(exist_ok=True)
        temp_root.mkdir(exist_ok=True)
        for old_so in lib_dir.glob(f"{spec.name}*.so"):
            old_so.unlink()
        (build_dir / "spec.json").write_text(json.dumps(asdict(spec)), encoding="utf-8")
        setup_path = build_dir / "setup.py"
        setup_path.write_text(_SETUP_SCRIPT, encoding="utf-8")

        nvcc = resolve_nvcc()
        env = dict(os.environ)
        for key in ("CPATH", "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH"):
            env.pop(key, None)
        env["CUDA_HOME"] = env["CUDA_PATH"] = str(Path(nvcc).resolve().parents[1])
        major, minor = torch.cuda.get_device_capability()
        env["TORCH_CUDA_ARCH_LIST"] = f"{major}.{minor}"
        env.setdefault("MAX_JOBS", DEFAULT_MAX_JOBS)
        with tempfile.TemporaryDirectory(
            dir=temp_root, prefix=f"build-{os.getpid()}-", ignore_cleanup_errors=True
        ) as temp_dir:
            subprocess.run(
                [
                    sys.executable,
                    str(setup_path),
                    "build_ext",
                    "--build-lib",
                    str(lib_dir),
                    "--build-temp",
                    temp_dir,
                ],
                cwd=str(build_dir),
                env=env,
                check=True,
            )
        so_path = _built_so(build_dir, spec.name)
        if so_path is None:
            raise RuntimeError(f"Build of {spec.name} produced no .so in {lib_dir}")
        (build_dir / SIGNATURE_FILE).write_text(signature, encoding="utf-8")
        return so_path


def load_extension(name: str, so_path: Path) -> ModuleType:
    if (module := sys.modules.get(name)) is not None:
        return module
    module_spec = importlib.util.spec_from_file_location(name, so_path)
    if module_spec is None or module_spec.loader is None:
        raise RuntimeError(f"Cannot load {name} from {so_path}")
    module = importlib.util.module_from_spec(module_spec)
    sys.modules[name] = module
    module_spec.loader.exec_module(module)
    return module


def build_dir_from_env(env_var: str, default_leaf: str) -> Path:
    return Path(os.environ.get(env_var, DEFAULT_CACHE_ROOT / default_leaf))
